#!/usr/bin/env node
// Farvelæg's line art → a transparent line layer + a lossless region label map (Krea PRD-01 §4.4).
//
//   node scripts/krea-regions.mjs            # all pages in kreaPages.ts
//   node scripts/krea-regions.mjs hund ugle  # just these
//   node scripts/krea-regions.mjs --report   # measure only, write nothing
//
// In:  art-src/krea/pages/<id>.jpg (the owner's Gemini line art, black on white).
// Out: src/assets/games/krea/pages/<id>.line.webp   lines only, transparent elsewhere
//      src/assets/games/krea/pages/<id>.regions.png region id in R + G×256 — LOSSLESS, never WebP
//      src/config/kreaPageRegions.ts                region counts + boxes, read by the game and tests
//
// The labelling is `src/components/krea/canvas/regionLabel.ts` (unit-tested). A page whose art has
// drifted into grey shading or texture is REJECTED (exit 1), never thresholded into speckle: re-render.

import sharp from 'sharp'
import { mkdir, writeFile } from 'node:fs/promises'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { GREY_REJECT, UNFILLABLE, greyShare, labelRegions } from '../src/components/krea/canvas/regionLabel.ts'
import { KREA_PAGES } from '../src/config/kreaPages.ts'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SRC = join(ROOT, 'art-src/krea/pages')
const OUT = join(ROOT, 'src/assets/games/krea/pages')
const TABLE = join(ROOT, 'src/config/kreaPageRegions.ts')

/** Components under this share of the page become unfillable (§4.4 start value 1.5%, tuned by eye). */
const MIN_AREA = 0.0035

const args = process.argv.slice(2)
const report = args.includes('--report')
const only = args.filter((a) => !a.startsWith('--'))
const pages = KREA_PAGES.filter((p) => !only.length || only.includes(p.id))

const table = {}
let failed = false
if (!report) await mkdir(OUT, { recursive: true })
for (const page of pages) {
  const { data, info } = await sharp(join(SRC, `${page.id}.jpg`)).greyscale().raw().toBuffer({ resolveWithObject: true })
  const { width: w, height: h } = info
  const lum = new Uint8Array(data.buffer, data.byteOffset, w * h)
  const grey = greyShare(lum, w, h)
  const map = labelRegions(lum, w, h, { minArea: MIN_AREA * w * h, outside: page.outside })
  const smallest = Math.min(...map.areas)
  console.log(
    `${page.id.padEnd(12)} ${w}×${h}  grey ${(grey * 100).toFixed(2)}%  regions ${String(map.count).padStart(3)}  smallest ${(smallest / (w * h) * 100).toFixed(2)}%`,
  )
  if (grey > GREY_REJECT) {
    console.error(`  REJECTED: ${(grey * 100).toFixed(1)}% stray mid-grey (> ${GREY_REJECT * 100}%) — shading or texture; re-render the page`)
    failed = true
    continue
  }
  if (report) continue

  // The line layer: black, alpha = how dark the source pixel is, so anti-aliased edges stay smooth.
  const rgba = Buffer.alloc(w * h * 4)
  for (let i = 0; i < w * h; i++) {
    const a = Math.max(0, Math.min(255, Math.round(((235 - lum[i]) / (235 - 60)) * 255)))
    rgba[i * 4 + 3] = a
  }
  await sharp(rgba, { raw: { width: w, height: h, channels: 4 } }).webp({ lossless: true }).toFile(join(OUT, `${page.id}.line.webp`))

  const ids = Buffer.alloc(w * h * 3)
  for (let i = 0; i < w * h; i++) {
    const v = map.labels[i]
    ids[i * 3] = v & 0xff
    ids[i * 3 + 1] = v >> 8
  }
  await sharp(ids, { raw: { width: w, height: h, channels: 3 } }).png({ compressionLevel: 9, palette: false }).toFile(join(OUT, `${page.id}.regions.png`))
  table[page.id] = { w, h, count: map.count, boxes: map.boxes }
}

if (failed) process.exit(1)
if (!report && pages.length === KREA_PAGES.length) {
  const body = Object.entries(table)
    .map(([id, t]) => `  ${id}: { w: ${t.w}, h: ${t.h}, count: ${t.count}, boxes: ${JSON.stringify(t.boxes)} },`)
    .join('\n')
  await writeFile(
    TABLE,
    `// GENERATED by scripts/krea-regions.mjs — do not edit. Farvelæg's regions per page (Krea PRD-01 §4.4):\n` +
      `// the label map's size, the region count, and each region's box [x0, y0, x1, y1] (id = index + 1).\n` +
      `// Label values: 0 = line, ${UNFILLABLE} = paper you can't colour.\n\n` +
      `export interface PageRegions {\n  w: number\n  h: number\n  count: number\n  boxes: Array<[number, number, number, number]>\n}\n\n` +
      `export const PAGE_REGIONS: Record<string, PageRegions> = {\n${body}\n}\n`,
  )
  console.log(`wrote ${TABLE}`)
} else if (!report) {
  console.log('(partial run: kreaPageRegions.ts not rewritten — run without page ids to regenerate it)')
}
