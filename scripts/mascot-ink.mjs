// Measures where the corner mascot's VISIBLE INK sits inside each baked sprite and writes
// `src/theme/mascotInk.ts` (owner, 2026-11-05: "the mascot is too far right on some screens and themes —
// evenly placed from left and bottom").
//
// The sprites are keyed cutouts with very different transparent padding per skin and pose, so a box
// pinned 6px from the corner put the ink anywhere from ~10 to ~40px in. The components now place the
// INK, not the box: they shift the image by these fractions so the ink's left and bottom edges land on
// one shared inset. Run after re-keying any mascot art:  node scripts/mascot-ink.mjs
// `mascotInk.test.ts` re-measures the files and fails if this table is stale.
import sharp from 'sharp'
import { writeFileSync } from 'node:fs'

const THEMES = ['kid', 'ocean', 'space', 'dino']
const POSES = ['mascot', 'mascot-idle', 'mascot-greet', 'mascot-point', 'mascot-celebrate']
// The alpha a pixel needs to count as ink: the drop-shadow is CSS, so anything fainter is keying fringe.
export const INK_ALPHA = 40

export async function inkBox(file) {
  const { data, info } = await sharp(file).ensureAlpha().raw().toBuffer({ resolveWithObject: true })
  const { width: w, height: h } = info
  let x0 = w, y0 = h, x1 = -1, y1 = -1
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      if (data[(y * w + x) * 4 + 3] > INK_ALPHA) {
        if (x < x0) x0 = x
        if (x > x1) x1 = x
        if (y < y0) y0 = y
        if (y > y1) y1 = y
      }
    }
  }
  const r = (v) => Math.round(v * 1000) / 1000
  return { w, h, left: r(x0 / w), right: r((w - 1 - x1) / w), top: r(y0 / h), bottom: r((h - 1 - y1) / h) }
}

export async function measureAll() {
  const out = {}
  for (const t of THEMES) {
    out[t] = {}
    for (const p of POSES) out[t][p] = await inkBox(`src/assets/themes/${t}/${p}.webp`)
  }
  return out
}

if (import.meta.url === `file:///${process.argv[1].replace(/\\/g, '/')}` || process.argv[1]?.endsWith('mascot-ink.mjs')) {
  const all = await measureAll()
  const lines = []
  for (const [t, poses] of Object.entries(all)) {
    lines.push(`  ${t}: {`)
    for (const [p, b] of Object.entries(poses)) {
      lines.push(`    '${p}': { w: ${b.w}, h: ${b.h}, left: ${b.left}, right: ${b.right}, top: ${b.top}, bottom: ${b.bottom} },`)
    }
    lines.push('  },')
  }
  const ts = `// GENERATED by \`node scripts/mascot-ink.mjs\` — do not edit by hand (mascotInk.test.ts re-measures).
//
// Where the visible ink sits inside each baked mascot sprite, as fractions of the image's own size:
// \`left\` = transparent share left of the ink, \`bottom\` = below it, etc. The corner mascot uses these to
// put its INK (not its image box) at one shared inset from the left and bottom edges.
export interface InkBox { w: number; h: number; left: number; right: number; top: number; bottom: number }
export type MascotSprite = 'mascot' | 'mascot-idle' | 'mascot-greet' | 'mascot-point' | 'mascot-celebrate'

export const MASCOT_INK: Record<string, Record<MascotSprite, InkBox>> = {
${lines.join('\n')}
}
`
  writeFileSync('src/theme/mascotInk.ts', ts)
  console.log(JSON.stringify(all, null, 1))
}
