import type { InkBox } from '../../theme/mascotInk'

// The square footprint the corner companion (`Mascot`) occupies in the bottom-left corner.
//
// It is `position: fixed` with `pointer-events: none`, so a game whose play surface FILLS the viewport
// cannot position itself "around" it — it has to RESERVE this band. That is the rule in
// `.claude/rules/responsive-design.md`: reserve the space, don't tune a percentage. Sammenlign Tal's
// answer tiles were measured overlapping the companion by 94×34px at 1024×768 while they were sized to
// fill the body, and no `maxHeight` tuned for that viewport would have held at 768×1024.
//
// Its tiles later shrank, so that specific overlap no longer reproduces there — the reservation is now
// the thing that keeps a future size increase from bringing it back. Reserve this, don't re-measure.
//
// Its own module (not an export from `Mascot.tsx`) so `Mascot` stays a component-only file for
// react-refresh, and so the value is importable without pulling in the component.
//
// Phone LANDSCAPE hides the companion entirely (`PHONE_LANDSCAPE` in Mascot's sx) → reserve nothing.
export const MASCOT_CORNER_SIZE = { xs: 84, md: 120 } as const
export const MASCOT_CORNER_PHONE_PORTRAIT = 52

// WHERE THE INK SITS, not where the box sits (owner, 2026-11-05: "too far right on some screens and
// themes — evenly placed from left and bottom"). The baked sprites carry very different transparent
// padding — a tall pose `contain`-ed in a square box is centred with ~17% of empty box beside it, a
// padded square sprite has 3–24% under it — so one box inset put the visible figure anywhere from 6 to
// ~34px in. Every corner mascot (home, the section menus, in game) now pins its box to the CORNER and
// shifts the image by its own measured ink box (`MASCOT_INK`, generated by `scripts/mascot-ink.mjs`), so
// the ink's left and bottom edges both land at this share of the box size: one rule, equal on both
// axes, scaling with the mascot rather than tuned per viewport.
export const MASCOT_INK_INSET = 0.12

/**
 * Absolute-position sx for a mascot `<img>` filling a SQUARE box, so its ink's left and bottom edges land
 * `MASCOT_INK_INSET` of the box in from the box's left and bottom. `objectFit: contain` anchored
 * left-bottom; percentages of `left`/`bottom` resolve against the square box, so one value holds at
 * every size.
 */
export function inkPlacementSx(ink: InkBox) {
  // The rendered image's share of the square box (contain): the long side fills it.
  const fw = Math.min(1, ink.w / ink.h)
  const fh = Math.min(1, ink.h / ink.w)
  const pct = (v: number) => `${Math.round(v * 10000) / 100}%`
  return {
    position: 'absolute',
    width: '100%',
    height: '100%',
    objectFit: 'contain',
    objectPosition: 'left bottom',
    left: pct(MASCOT_INK_INSET - ink.left * fw),
    bottom: pct(MASCOT_INK_INSET - ink.bottom * fh),
  } as const
}
